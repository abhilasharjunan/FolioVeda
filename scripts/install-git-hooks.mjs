#!/usr/bin/env node
/**
 * Installs prepare-commit-msg + post-commit so version and Version History
 * update on every commit and land in the same commit.
 * Safe to re-run (overwrites the local hook wrappers only).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const hooksDir = path.join(root, ".git", "hooks");

function writeHook(name, scriptFile) {
  const hookPath = path.join(hooksDir, name);
  const wrapper = `#!/usr/bin/env node
// Auto-generated by scripts/install-git-hooks.mjs - do not edit by hand.
const { spawnSync } = require("child_process");
const path = require("path");

const script = path.join(__dirname, "../../scripts/${scriptFile}");
const result = spawnSync(process.execPath, [script, ...process.argv.slice(2)], {
  stdio: "inherit",
});
process.exit(result.status ?? 1);
`;
  fs.writeFileSync(hookPath, wrapper, { mode: 0o755 });
  console.log(`✓ Installed git hook: ${path.relative(root, hookPath)}`);
}

fs.mkdirSync(hooksDir, { recursive: true });
writeHook("prepare-commit-msg", "prepare-commit-msg.mjs");
writeHook("post-commit", "post-commit.mjs");
